import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.bukkit.configuration.file.YamlConfiguration;

import java.nio.file.*;
import java.io.IOException;
import java.util.*;

import static org.junit.jupiter.api.Assertions.*;

class DeathBackupsTest {
    @TempDir
    Path root;
    private static final String OWNER = "0123456789abcdef0123456789abcdef";

    private record Fixture(Path plugin, Path state, Path snapshot, Path worldFile, DeathBackups backups) {
    }

    private Fixture readyBackup() throws Exception {
        Path level = Files.createDirectory(root.resolve("world"));
        Path plugin = Files.createDirectory(root.resolve("plugin"));
        List<Path> worlds = new ArrayList<>();
        for (String suffix : List.of("", "_nether", "_the_end")) {
            Path world = Files.createDirectories(level.resolve("dimensions/minecraft/hcr_" + OWNER + "_3" + suffix));
            Files.writeString(world.resolve("chunk.dat"), "saved house");
            worlds.add(world);
        }
        var state = new YamlConfiguration();
        state.set("world-id", OWNER);
        state.set("run", 3L);
        var backups = new DeathBackups(plugin, level);
        Path snapshot = backups.prepare(state, worlds);
        backups.finish(snapshot);
        Path worldFile = worlds.getFirst().resolve("chunk.dat");
        Files.writeString(worldFile, "current house");
        Path stateFile = plugin.resolve("state.yml");
        state.set("run", 4L);
        state.save(stateFile.toFile());
        backups.request(snapshot.getFileName().toString());
        return new Fixture(plugin, stateFile, snapshot, worldFile, backups);
    }

    @Test
    void damagedPlayerDirectoryIsDetectedBeforeAnyWorldIsReplaced() throws Exception {
        Fixture fixture = readyBackup();
        Files.delete(fixture.snapshot().resolve("stats")); // Empty directory generated by prepare().
        assertThrows(IOException.class, () -> fixture.backups().restoreRequested(fixture.state()));
        assertEquals("current house", Files.readString(fixture.worldFile()));
        assertEquals(4L, YamlConfiguration.loadConfiguration(fixture.state().toFile()).getLong("run"));
        assertTrue(Files.exists(fixture.plugin().resolve("death-backups/restore-request")));
    }

    @Test
    void inconsistentSnapshotStateIsRejectedBeforeReplacingWorlds() throws Exception {
        Fixture fixture = readyBackup();
        Path savedState = fixture.snapshot().resolve("state.yml");
        var state = YamlConfiguration.loadConfiguration(savedState.toFile());
        state.set("run", 999L);
        state.save(savedState.toFile());
        assertThrows(IOException.class, () -> fixture.backups().restoreRequested(fixture.state()));
        assertEquals("current house", Files.readString(fixture.worldFile()));
        assertEquals(4L, YamlConfiguration.loadConfiguration(fixture.state().toFile()).getLong("run"));
    }

    @Test
    void restoresWorldsPlayersAndAttemptAndKeepsCurrentSafetyCopy() throws Exception {
        Path level = Files.createDirectories(root.resolve("world"));
        Path plugin = Files.createDirectories(root.resolve("plugins/HardcoreReset"));
        Path player = Files.createDirectories(level.resolve("playerdata")).resolve("player.dat");
        Files.writeString(player, "alive with diamonds");
        List<Path> worlds = new ArrayList<>();
        for (String suffix : List.of("", "_nether", "_the_end")) {
            Path world = Files.createDirectories(level.resolve("dimensions/minecraft/hcr_" + OWNER + "_3" + suffix));
            Files.writeString(world.resolve("chunk.dat"), "house before death");
            worlds.add(world);
        }
        YamlConfiguration saved = new YamlConfiguration();
        saved.set("world-id", OWNER);
        saved.set("run", 3L);
        saved.set("seconds", 123L);
        saved.set("rollback-revive", "player-uuid");
        DeathBackups backups = new DeathBackups(plugin, level);
        Path snapshot = backups.prepare(saved, worlds);
        assertTrue(backups.list().isEmpty(), "Incomplete backup must never be offered for rollback");
        backups.finish(snapshot);
        Files.writeString(player, "new run empty inventory");
        Files.writeString(worlds.getFirst().resolve("chunk.dat"), "changed after backup");
        saved.set("run", 4L);
        saved.set("highest-run", 4L);
        saved.set("reset-pending", true);
        Path state = plugin.resolve("state.yml");
        saved.save(state.toFile());
        backups.requestLatest();
        assertTrue(backups.restoreRequested(state));
        assertEquals("alive with diamonds", Files.readString(player));
        assertEquals("house before death", Files.readString(worlds.getFirst().resolve("chunk.dat")));
        var restored = YamlConfiguration.loadConfiguration(state.toFile());
        assertEquals(3L, restored.getLong("run"));
        assertEquals(4L, restored.getLong("highest-run"));
        assertEquals(123L, restored.getLong("seconds"));
        assertEquals("player-uuid", restored.getString("rollback-revive"));
        assertFalse(restored.getBoolean("reset-pending"));
        assertFalse(backups.restoreRequested(state));
        try (var files = Files.list(plugin.resolve("death-backups"))) {
            Path safety = files.filter(p -> p.getFileName().toString().startsWith("safety-")).findFirst().orElseThrow();
            assertEquals("new run empty inventory", Files.readString(safety.resolve("playerdata/player.dat")));
        }
    }

    @Test
    void refusesRequestTraversal() throws Exception {
        Path level = Files.createDirectory(root.resolve("world"));
        Path plugin = Files.createDirectory(root.resolve("plugin"));
        DeathBackups backups = new DeathBackups(plugin, level);
        Files.writeString(plugin.resolve("death-backups/restore-request"), "../../outside");
        assertThrows(IOException.class, () -> backups.restoreRequested(plugin.resolve("state.yml")));
    }

    @Test
    void menuCanSelectSpecificOlderBackupAndCannotSelectIncompleteBackup() throws Exception {
        Path level = Files.createDirectory(root.resolve("world"));
        Path plugin = Files.createDirectory(root.resolve("plugin"));
        List<Path> worlds = new ArrayList<>();
        for (String suffix : List.of("", "_nether", "_the_end"))
            worlds.add(Files.createDirectories(level.resolve("dimensions/minecraft/hcr_" + OWNER + "_3" + suffix)));
        var state = new YamlConfiguration();
        state.set("world-id", OWNER);
        state.set("run", 3L);
        DeathBackups backups = new DeathBackups(plugin, level);
        Path first = backups.prepare(state, worlds);
        backups.finish(first);
        Path second = backups.prepare(state, worlds);
        backups.finish(second);
        Path incomplete = backups.prepare(state, worlds);
        backups.request(first.getFileName().toString());
        assertEquals(first.getFileName().toString(), Files.readString(plugin.resolve("death-backups/restore-request")));
        assertThrows(IOException.class, () -> backups.request(incomplete.getFileName().toString()));
        assertThrows(IOException.class, () -> backups.request("../../other"));
    }

    @Test
    void refusesFinishingBackupOfUnrelatedDirectory() throws Exception {
        Path level = Files.createDirectory(root.resolve("world"));
        Path plugin = Files.createDirectory(root.resolve("plugin"));
        Path unrelated = Files.createDirectory(root.resolve("important"));
        var state = new YamlConfiguration();
        state.set("world-id", OWNER);
        state.set("run", 3L);
        DeathBackups backups = new DeathBackups(plugin, level);
        Path snapshot = backups.prepare(state, List.of(unrelated, unrelated, unrelated));
        assertThrows(IOException.class, () -> backups.finish(snapshot));
        assertTrue(backups.list().isEmpty());
        assertTrue(Files.exists(unrelated));
    }
}
